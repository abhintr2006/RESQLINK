export const getCategoryTranslation = (category: EmergencyCategory, lang: LanguageCode): CategoryTranslation => {
  const byCat = CATEGORY_TRANSLATIONS[category];
  if (!byCat) return { name: category, desc: '' };
  return byCat[lang] || byCat.en || { name: category, desc: '' };
};

export const t = (key: string, lang: LanguageCode): string => {
  const entry = UI_TRANSLATIONS[key];
  if (!entry) return key;
  return entry[lang] || entry.en || key;
};
